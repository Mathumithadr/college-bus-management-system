const mongoose = require('mongoose');

const reportSchema = new mongoose.Schema(
  {
    ticketId: {
      type: String,
      required: true,
      unique: true,
      trim: true, // Auto-generated by service layer: TICK-YYYY-NNNN
    },
    studentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'Student is required'],
    },
    category: {
      type: String,
      required: [true, 'Category is required'],
      enum: [
        'bus_delay',
        'driver_staff_behaviour',
        'bus_condition',
        'route_stop_issue',
        'other',
      ],
    },
    subject: {
      type: String,
      required: [true, 'Subject is required'],
      trim: true,
      maxlength: [200, 'Subject cannot exceed 200 characters'],
    },
    description: {
      type: String,
      required: [true, 'Description is required'],
      trim: true,
      maxlength: [2000, 'Description cannot exceed 2000 characters'],
    },
    busId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Bus',
      default: null,
    },
    routeId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Route',
      default: null,
    },
    tripId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Trip',
      default: null,
    },
    // photoAttachments removed for V1 — no file storage backend defined
    status: {
      type: String,
      enum: [
        'submitted',
        'under_review',
        'more_information_required',
        'resolved',
        'rejected',
        'closed',
      ],
      default: 'submitted',
    },
    adminNote: {
      type: String,
      trim: true,
      maxlength: [1000, 'Admin note cannot exceed 1000 characters'],
      default: null,
    },
    resolution: {
      type: String,
      trim: true,
      maxlength: [1000, 'Resolution cannot exceed 1000 characters'],
      default: null,
    },
    parentReportId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Report',
      default: null, // Links a dispute follow-up ticket to the original
    },
    closedAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
    collection: 'reports',
  }
);

reportSchema.index({ studentId: 1, createdAt: -1 });
reportSchema.index({ status: 1, createdAt: -1 });
reportSchema.index({ parentReportId: 1 });

module.exports = mongoose.model('Report', reportSchema);